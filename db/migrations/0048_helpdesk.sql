-- Help desk: answers HR keeps (any language), team contacts, office locations, the organisation's social links.
-- Nothing is deleted: rows are switched off (active = 0) and every change is in hd_log.
CREATE TABLE IF NOT EXISTS hd_topic (
  id INT AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(40) NOT NULL,
  lang VARCHAR(8) NOT NULL DEFAULT 'en',
  title VARCHAR(160) NOT NULL,
  keywords VARCHAR(600) NOT NULL DEFAULT '',
  answer TEXT NOT NULL,
  module_key VARCHAR(40) NOT NULL DEFAULT '',
  sort INT NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  seeded TINYINT(1) NOT NULL DEFAULT 0,
  updated_by INT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_slug (slug, lang)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS hd_office (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL,
  kind VARCHAR(12) NOT NULL DEFAULT 'branch',
  branch_id INT NULL,
  address VARCHAR(300) NOT NULL DEFAULT '',
  map_url VARCHAR(500) NOT NULL DEFAULT '',
  review_url VARCHAR(500) NOT NULL DEFAULT '',
  phone VARCHAR(16) NOT NULL DEFAULT '',
  sort INT NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  updated_by INT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS hd_contact (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  dept VARCHAR(60) NOT NULL DEFAULT '',
  role VARCHAR(60) NOT NULL DEFAULT '',
  mobile VARCHAR(16) NOT NULL DEFAULT '',
  email VARCHAR(120) NOT NULL DEFAULT '',
  whatsapp TINYINT(1) NOT NULL DEFAULT 0,
  linkedin VARCHAR(300) NOT NULL DEFAULT '',
  office_ids VARCHAR(120) NOT NULL DEFAULT '',
  sort INT NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  updated_by INT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS hd_social (
  platform VARCHAR(16) PRIMARY KEY,
  url VARCHAR(500) NOT NULL DEFAULT '',
  updated_by INT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS hd_log (
  id INT AUTO_INCREMENT PRIMARY KEY,
  at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  by_id INT NOT NULL,
  what VARCHAR(12) NOT NULL,
  item_id VARCHAR(40) NOT NULL,
  act VARCHAR(10) NOT NULL,
  fields VARCHAR(300) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
