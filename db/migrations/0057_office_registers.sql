-- Office registers: counted property each branch holds, and a book library with lending.
CREATE TABLE IF NOT EXISTS office_prop (
  id INT AUTO_INCREMENT PRIMARY KEY, branch_id INT NULL, no VARCHAR(10) NOT NULL DEFAULT '', name VARCHAR(160) NOT NULL,
  labels VARCHAR(120) NOT NULL DEFAULT '', qty INT NOT NULL DEFAULT 1, place VARCHAR(160) NOT NULL DEFAULT '', notes VARCHAR(500) NOT NULL DEFAULT '',
  active TINYINT NOT NULL DEFAULT 1, off_reason VARCHAR(200) NOT NULL DEFAULT '', updated_by INT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, KEY k_branch (branch_id, active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS office_book (
  id INT AUTO_INCREMENT PRIMARY KEY, branch_id INT NULL, no VARCHAR(10) NOT NULL DEFAULT '', type VARCHAR(40) NOT NULL DEFAULT '',
  title VARCHAR(160) NOT NULL, author VARCHAR(120) NOT NULL DEFAULT '', language VARCHAR(40) NOT NULL DEFAULT '', copies INT NOT NULL DEFAULT 1,
  active TINYINT NOT NULL DEFAULT 1, off_reason VARCHAR(200) NOT NULL DEFAULT '', updated_by INT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, KEY k_branch (branch_id, active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS office_book_issue (
  id INT AUTO_INCREMENT PRIMARY KEY, book_id INT NOT NULL, emp_code VARCHAR(30) NULL, person VARCHAR(120) NOT NULL,
  issued DATE NOT NULL, due DATE NULL, returned DATE NULL, note VARCHAR(200) NOT NULL DEFAULT '',
  created_by INT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, returned_by INT NULL,
  KEY k_book (book_id, returned), KEY k_emp (emp_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS office_reg_log (
  id INT AUTO_INCREMENT PRIMARY KEY, what VARCHAR(10) NOT NULL, ref_id INT NOT NULL, act VARCHAR(20) NOT NULL,
  fields VARCHAR(255) NOT NULL DEFAULT '', by_user INT NULL, at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY k_ref (what, ref_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
