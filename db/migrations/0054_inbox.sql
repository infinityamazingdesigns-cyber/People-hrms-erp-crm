-- Inbox: each login's own mail (Zoho Mail, Gmail), Zoho Cliq and WhatsApp Business connections.
CREATE TABLE IF NOT EXISTS ib_acct (
  uid INT NOT NULL, svc VARCHAR(10) NOT NULL, client_id VARCHAR(190) NOT NULL DEFAULT '', dc VARCHAR(10) NOT NULL DEFAULT 'com',
  box TEXT NULL, info TEXT NULL, hint VARCHAR(12) NOT NULL DEFAULT '', connected TINYINT NOT NULL DEFAULT 0,
  last_err VARCHAR(255) NOT NULL DEFAULT '', updated_by INT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, PRIMARY KEY (uid, svc)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ib_log (
  id INT AUTO_INCREMENT PRIMARY KEY, uid INT NOT NULL DEFAULT 0, svc VARCHAR(10) NOT NULL, act VARCHAR(40) NOT NULL,
  by_user INT NULL, note VARCHAR(255) NOT NULL DEFAULT '', at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY k_at (at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ib_wa_msg (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, uid INT NOT NULL, mid VARCHAR(190) NOT NULL, peer VARCHAR(20) NOT NULL,
  name VARCHAR(120) NOT NULL DEFAULT '', dir VARCHAR(3) NOT NULL, src VARCHAR(10) NOT NULL, type VARCHAR(20) NOT NULL DEFAULT 'text',
  body TEXT NULL, ts INT NOT NULL, status VARCHAR(12) NOT NULL DEFAULT '', by_user INT NULL, seen TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_mid (uid, mid), KEY k_peer (uid, peer, ts), KEY k_ts (ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ib_wa_hook (
  hash CHAR(64) PRIMARY KEY, at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
