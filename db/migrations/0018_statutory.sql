-- Statutory compliance: official links, due-date rules, registrations, monthly spends pulled from locked payroll,
-- payments and filings. Nothing is deleted: rows are switched off; a payment or filing taken back keeps its row;
-- st_log is append-only. The country pack seeds links, dues and registrations once by key (st_seed()).

CREATE TABLE IF NOT EXISTS st_portal (
  id INT AUTO_INCREMENT PRIMARY KEY, seed VARCHAR(20) NULL UNIQUE,
  scheme VARCHAR(8) NOT NULL, state VARCHAR(40) NOT NULL DEFAULT '', audience VARCHAR(4) NOT NULL,
  name VARCHAR(120) NOT NULL, url VARCHAR(400) NOT NULL, note VARCHAR(300) NOT NULL DEFAULT '',
  checked TINYINT(1) NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1, sort INT NOT NULL DEFAULT 0,
  updated_by INT NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS st_due (
  id INT AUTO_INCREMENT PRIMARY KEY, seed VARCHAR(20) NULL UNIQUE,
  scheme VARCHAR(8) NOT NULL, state VARCHAR(40) NOT NULL DEFAULT '', label VARCHAR(120) NOT NULL,
  day TINYINT NOT NULL DEFAULT 15, months VARCHAR(40) NOT NULL DEFAULT '', on_date DATE NULL, after_m TINYINT NOT NULL DEFAULT 1,
  kind VARCHAR(5) NOT NULL DEFAULT 'pay', who VARCHAR(10) NOT NULL DEFAULT '', note VARCHAR(300) NOT NULL DEFAULT '',
  checked TINYINT(1) NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1,
  updated_by INT NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS st_reg (
  id INT AUTO_INCREMENT PRIMARY KEY, seed VARCHAR(20) NULL UNIQUE,
  scheme VARCHAR(8) NOT NULL, state VARCHAR(40) NOT NULL DEFAULT '', label VARCHAR(80) NOT NULL,
  number VARCHAR(60) NOT NULL DEFAULT '', valid_till DATE NULL, note VARCHAR(300) NOT NULL DEFAULT '', active TINYINT(1) NOT NULL DEFAULT 1,
  updated_by INT NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS st_spend (
  id INT AUTO_INCREMENT PRIMARY KEY, ym CHAR(7) NOT NULL, scheme VARCHAR(8) NOT NULL, state VARCHAR(40) NOT NULL DEFAULT '',
  people INT NOT NULL DEFAULT 0, ee DECIMAL(12,2) NOT NULL DEFAULT 0, er DECIMAL(12,2) NOT NULL DEFAULT 0, charges DECIMAL(12,2) NOT NULL DEFAULT 0,
  src VARCHAR(8) NOT NULL DEFAULT 'payroll', pulled TEXT NULL, pulled_at DATETIME NULL, note VARCHAR(300) NOT NULL DEFAULT '',
  paid_on DATE NULL, paid_ref VARCHAR(60) NOT NULL DEFAULT '', paid_amt DECIMAL(12,2) NULL, paid_mode VARCHAR(12) NOT NULL DEFAULT '',
  paid_by INT NULL, paid_at DATETIME NULL, updated_by INT NULL, updated_at DATETIME NULL,
  UNIQUE KEY u_row (ym, scheme, state), KEY k_ym (ym)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS st_filing (
  id INT AUTO_INCREMENT PRIMARY KEY, rule_id INT NOT NULL, period VARCHAR(10) NOT NULL, step VARCHAR(10) NOT NULL,
  on_date DATE NOT NULL, ref VARCHAR(80) NOT NULL DEFAULT '', note VARCHAR(300) NOT NULL DEFAULT '',
  reverted TINYINT(1) NOT NULL DEFAULT 0, revert_reason VARCHAR(300) NOT NULL DEFAULT '',
  by_user INT NOT NULL, at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY k_rule (rule_id, period)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS st_log (
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NULL, entity VARCHAR(8) NOT NULL, entity_id INT NOT NULL, action VARCHAR(20) NOT NULL,
  detail TEXT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY k_ent (entity, entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
